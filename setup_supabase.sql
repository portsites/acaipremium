-- SCRIPT DE CONFIGURAÇÃO DO BANCO DE DADOS - AÇAÍ PREMIUM (SUPABASE)
-- Como usar:
-- 1. No painel do Supabase, clique em "SQL Editor" no menu lateral esquerdo.
-- 2. Clique em "+ New query".
-- 3. Cole todo este código abaixo e clique no botão "Run" (ou Ctrl + Enter).
-- ============================================================================

-- 1. CRIAR A TABELA DE PEDIDOS
create table if not exists public.pedidos (
    id bigint generated by default as identity primary key,
    codigo_pedido text not null,
    created_at timestamptz not null default now(),
    cliente_nome text not null,
    cliente_telefone text not null,
    tipo_entrega text not null check (tipo_entrega in ('entrega', 'retirada')),
    endereco text,
    forma_pagamento text not null check (forma_pagamento in ('pix', 'cartao', 'dinheiro')),
    troco_para text,
    subtotal numeric(10,2) not null default 0,
    taxa_entrega numeric(10,2) not null default 0,
    valor_total numeric(10,2) not null,
    itens jsonb not null default '[]'::jsonb,
    status text not null default 'Novo' check (
        status in (
            'Novo',
            'Em preparo',
            'Saiu para entrega',
            'Pronto',
            'Concluído',
            'Cancelado'
        )
    )
);

-- Índices para deixar os filtros de data e status super rápidos
create index if not exists idx_pedidos_created_at on public.pedidos (created_at desc);
create index if not exists idx_pedidos_status on public.pedidos (status);

-- ============================================================================
-- 2. REGRAS DE SEGURANÇA (ROW LEVEL SECURITY - RLS)
-- ============================================================================

-- Ativa a proteção por linha na tabela
alter table public.pedidos enable row level security;

-- Remove políticas antigas caso você rode o script mais de uma vez
drop policy if exists "Clientes podem enviar novos pedidos" on public.pedidos;
drop policy if exists "Somente admin pode ler pedidos" on public.pedidos;
drop policy if exists "Somente admin pode atualizar pedidos" on public.pedidos;
drop policy if exists "Somente admin pode excluir pedidos" on public.pedidos;

-- REGRA 1: Qualquer cliente no site (anon) pode APENAS ENVIAR (INSERT) pedidos novos
create policy "Clientes podem enviar novos pedidos"
on public.pedidos
for insert
to anon, authenticated
with check (
    status = 'Novo'
);

-- REGRA 2: SOMENTE a açaiteria logada (authenticated) pode LER (SELECT) os pedidos
create policy "Somente admin pode ler pedidos"
on public.pedidos
for select
to authenticated
using (true);

-- REGRA 3: SOMENTE a açaiteria logada (authenticated) pode ALTERAR (UPDATE) o status
create policy "Somente admin pode atualizar pedidos"
on public.pedidos
for update
to authenticated
using (true)
with check (true);

-- REGRA 4: SOMENTE a açaiteria logada (authenticated) pode EXCLUIR (DELETE) pedidos
create policy "Somente admin pode excluir pedidos"
on public.pedidos
for delete
to authenticated
using (true);

-- ============================================================================
-- 3. ATIVAR ATUALIZAÇÃO EM TEMPO REAL (REALTIME)
-- ============================================================================
do $$
begin
    if not exists (
        select 1
        from pg_publication_tables
        where pubname = 'supabase_realtime'
          and schemaname = 'public'
          and tablename = 'pedidos'
    ) then
        alter publication supabase_realtime add table public.pedidos;
    end if;
end $$;
